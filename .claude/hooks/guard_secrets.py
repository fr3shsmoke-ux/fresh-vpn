"""Не давать править файлы с боевыми секретами через ассистента.

Почему это нужно именно здесь: `.env.prod` лежит прямо в `miniapp/`, рядом
с обычным кодом. Там боевой токен бота, ключ панели Remnawave, секрет сессий
и строка подключения к базе. Одна невнимательная правка кладёт прод целиком,
а откатить нечем — файл не в системе версий.

Правка руками, глазами, с бэкапом — пожалуйста. Через ассистента — нет.

Ставится на PreToolUse. Код возврата 2 = правка не состоится, текст из stderr
уходит ассистенту как объяснение.
"""

import json
import re
import sys

# Что закрываем. Не только .env: ключи и сертификаты тоже мимо ассистента.
ОПАСНЫЕ = re.compile(
    r"(^|[/\\])\.env($|[.\w-]*)|\.(pem|key|p12|pfx|jks)$|(^|[/\\])id_(rsa|ed25519)$",
    re.IGNORECASE,
)


def main() -> int:
    try:
        вход = json.load(sys.stdin)
    except (json.JSONDecodeError, ValueError):
        return 0  # не поняли вход - молча пропускаем, хук не должен ломать работу

    путь = str((вход.get("tool_input") or {}).get("file_path") or "")
    if не_опасный(путь):
        return 0

    print(
        f"Правка «{путь}» остановлена: это файл с боевыми секретами.\n"
        "Правьте его руками на сервере или локально, с бэкапом. "
        "Значения ключей в чат не выводить — только имена.",
        file=sys.stderr,
    )
    return 2


def не_опасный(путь: str) -> bool:
    return not путь or not ОПАСНЫЕ.search(путь)


if __name__ == "__main__":
    sys.exit(main())
