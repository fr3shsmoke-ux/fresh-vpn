"""Сеть на секреты для ФИКСАЦИИ: ловит значения в содержимом того, что коммитим.

## Что уже было в дереве и чего не хватало

`.claude/hooks/guard_paths.py` — **проверяет содержимое** записи и отбивает
живые ключи; `.claude/hooks/guard_secrets.py` — закрывает **имена** файлов
(`.env`, `.pem`, `.key`). Обе стоят на `PreToolUse` для `Edit|Write`.

🔴 Разрыв не в правилах, а в **области**: сеть видит только записи ассистента.
Файл, положенный в дерево `scp`, `curl` или руками, её не встречает вовсе, а
фиксация не встречает никакой сети — `.git/hooks` пуст, `core.hooksPath` не
задан. 31.08.2026 так в коммит ушли четыре файла, снятые с боевого сервера:
ни одна проверка их не видела.

Отсюда правило, которому подчинён этот файл: запрет ставится там, где предмет
измерим целиком, — на **содержимом того, что фиксируется**, а не на именах
некоторых дорог к нему (М-33).

## Что ловит и чего не ловит (Ф-38)

Ноль этой сети означает «ни одно её правило не сработало», а не «секретов
нет». Область устанавливается **подложенными образцами**, а не этим текстом:
`--проба` подкладывает по образцу на каждое правило и требует поймать все.

Ловит: боевой токен бота Telegram, строку подключения с паролем, блок
приватного ключа, JWT, присваивание секретному имени длинного значения, ключ
AWS.

**Не ловит и не притворяется:** секрет, собранный из частей или из переменных;
значение в двоичном файле; пароль, похожий на обычное слово; форматы чужих
систем, о которых мы не знаем.

## Правило собственного носителя (М-9)

Правило, срабатывающее на собственном носителе, неприменимо: сеть, отбивающая
свой исходник, не даст себя зафиксировать. Решено **построением, а не
исключением**: образцы хранятся кусками и склеиваются в момент запуска, так
что в этом файле нет ни одного срабатывающего литерала. Исключение-маркер было
бы дырой, через которую проходит что угодно; отсутствие литерала дырой быть не
может. Проверяется пробой: сеть, натравленная на собственный исходник, обязана
дать ноль.

Запуск:

    python tools/сеть_на_секреты.py --фиксация          # то, что в индексе
    python tools/сеть_на_секреты.py --диапазон A..B     # содержимое коммитов
    python tools/сеть_на_секреты.py --проба             # калибровка образцами
    python tools/сеть_на_секреты.py файл [файл ...]
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")

КОРЕНЬ = Path(__file__).resolve().parents[1]

# Разделитель вывода git при `-z`. Именованной константой, а не литералом:
# нулевой байт в исходнике невидим глазом и ломается при копировании.
РАЗДЕЛИТЕЛЬ = "\x00"

# Правила. У каждого — имя, выражение и ОБРАЗЕЦ КУСКАМИ. Образец лежит рядом с
# правилом нарочно: правило без образца показаний не даёт, потому что
# неизвестно, ловит ли оно хоть что-нибудь. Куски склеиваются на запуске —
# см. «правило собственного носителя» в шапке.
ПРАВИЛА: list[tuple[str, re.Pattern[str], tuple[str, ...]]] = [
    (
        "токен бота Telegram",
        re.compile(r"\b\d{8,12}:[A-Za-z0-9_-]{35}\b"),
        ("8100000000", ":", "AAHdqTcvCH1vGWJxfSeofSAs0K5PALDs", "aw1"),
    ),
    (
        "строка подключения с паролем",
        re.compile(
            r"\b(?:mongodb(?:\+srv)?|postgres(?:ql)?|redis|amqp)://"
            r"[^\s:@/]+:[^\s@/]{4,}@"
        ),
        ("mongo", "db://", "user", ":", "nnnnnnnn", "@", "10.0.0.1:27017/db"),
    ),
    (
        "блок приватного ключа",
        re.compile(r"-----BEGIN (?:RSA |EC |OPENSSH |PGP )?PRIVATE ", re.IGNORECASE),
        ("-----BEGIN ", "OPENSSH ", "PRIVATE ", "KEY-----"),
    ),
    (
        "JWT",
        re.compile(r"\bey[A-Za-z0-9_-]{10,}\.ey[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}"),
        ("ey", "JhbGciOiJIUzI1NiJ9", ".", "ey", "JzdWIiOiIxMjM0NTYifQ", ".", "cccccccccccc"),
    ),
    (
        "секретное имя = длинное значение",
        re.compile(
            r"(?i)\b([A-Za-z_][A-Za-z0-9_]{2,40}"
            r"(?:token|secret|password|passwd|api_key|apikey|private_key|credential))\b"
            r"\s*[:=]\s*['\"]?([A-Za-z0-9_\-./+=]{16,})['\"]?"
        ),
        ("SOME_API", "_KEY", " = ", '"', "nnnnnnnnnnnnnnnnnnnn", '"'),
    ),
    (
        # AWS мы не пользуемся. Правило стоит как дешёвый ловец вставки из
        # чужой переписки: цена — одно выражение, польза — целый класс.
        "ключ доступа AWS",
        re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
        ("AKI", "A", "IOSFODNN7EXAMPLE"),
    ),
]

# 🔴 Ложные срабатывания, объявленные ПОИМЁННО и с причиной. Пустой список
# означал бы, что вопрос не задавали; список без причин — способ заглушить
# неудобное.
ИЗВЕСТНЫЕ_НЕ_СЕКРЕТЫ: list[tuple[str, str]] = [
    ("co-authored-by:", "подпись в сообщении коммита, не значение"),
]


def образец(куски: tuple[str, ...]) -> str:
    return "".join(куски)


def объявлен_не_секретом(строка: str) -> str:
    низ = строка.lower()
    for кусок, причина in ИЗВЕСТНЫЕ_НЕ_СЕКРЕТЫ:
        if кусок in низ:
            return причина
    return ""


def найти(текст: str, откуда: str) -> list[tuple[str, str, int, str]]:
    """Находки: (откуда, имя правила, номер строки, обрезанная строка).

    🔴 Само значение наружу НЕ печатается: строка обрезается, середина
    вырезается. Находка обязана быть опознаваемой человеком и при этом не
    переносить секрет в журнал, в чат и в отчёт — иначе сеть, ловящая утечку,
    сама становится дорогой утечки.
    """
    находки = []
    for н, строка in enumerate(текст.splitlines(), 1):
        if объявлен_не_секретом(строка):
            continue
        for имя, правило, _ in ПРАВИЛА:
            if правило.search(строка):
                кратко = строка.strip()
                if len(кратко) > 40:
                    кратко = кратко[:18] + " … " + кратко[-8:]
                находки.append((откуда, имя, н, кратко))
                break
    return находки


def прочитать(путь: Path) -> str:
    try:
        return путь.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def выполнить(команда: list[str]) -> str:
    готово = subprocess.run(
        команда, capture_output=True, text=True, encoding="utf-8",
        errors="replace", check=False, cwd=КОРЕНЬ,
    )
    if готово.returncode != 0:
        raise SystemExit(f"🔴 ОТКАЗ: {' '.join(команда)}\n{готово.stderr[:300]}")
    return готово.stdout


def из_индекса() -> list[tuple[str, str]]:
    """Файлы в индексе.

    🔴 `-z` и `core.quotepath=false` обязательны оба. Git по умолчанию
    экранирует не-ASCII пути в кавычки с восьмеричными кодами, а дерево здесь
    полно кириллических имён — `сеть_на_секреты.py`, `сверка_кода_с_боем.py`.
    Экранированное имя, поданное обратно в `git show`, не разрешается, и хук
    падал с «ambiguous argument». Отбой при этом происходил — но по причине
    «я сломан», а не «нашёл секрет», и эти исходы обязаны различаться.
    """
    сырое = выполнить([
        "git", "-c", "core.quotepath=false", "diff", "--cached",
        "-z", "--name-only", "--diff-filter=ACMR",
    ])
    имена = [и for и in сырое.split(РАЗДЕЛИТЕЛЬ) if и.strip()]
    return [(имя, выполнить(["git", "show", f":{имя}"])) for имя in имена]


def из_диапазона(диапазон: str) -> list[tuple[str, str]]:
    """Содержимое КАЖДОЙ версии КАЖДОГО файла в коммитах диапазона.

    Не диффы. Утверждение о том, что секрет не попал в историю, снимается
    запросом к истории, а не к описи настоящего момента (М-39): файл, стёртый
    следующим коммитом, в описи не значится и в истории лежит.
    """
    коммиты = [к for к in выполнить(["git", "rev-list", диапазон]).splitlines() if к.strip()]
    итог: list[tuple[str, str]] = []
    видели: set[str] = set()
    for коммит in коммиты:
        # `-z`: разделитель NUL, имя не экранируется и не ломается о пробелы.
        сырое = выполнить(["git", "ls-tree", "-r", "-z", коммит])
        for запись in сырое.split(РАЗДЕЛИТЕЛЬ):
            if not запись.strip():
                continue
            голова, _, имя = запись.partition("	")
            части = голова.split()
            if len(части) < 3 or not имя:
                continue
            ключ = части[2]
            if ключ in видели:
                continue  # тот же блоб уже проверен под другим коммитом
            видели.add(ключ)
            итог.append((f"{коммит[:7]}:{имя}", выполнить(["git", "cat-file", "-p", ключ])))
    print(f"коммитов в диапазоне: {len(коммиты)} · разных версий файлов: {len(итог)}")
    return итог


def проба() -> int:
    """🔴 Калибровка: подложено K, поймано K, пропущено 0 — и три половины.

      · положительная — каждое правило обязано поймать свой образец;
      · отрицательная — чистый текст обязан пройти без единой находки;
      · собственный носитель — сеть на своём исходнике обязана дать ноль,
        иначе она не даст себя зафиксировать (М-9).
    """
    подложено = поймано = 0
    пропущенные = []
    for имя, _, куски in ПРАВИЛА:
        подложено += 1
        свои = [н for н in найти(образец(куски), "проба") if н[1] == имя]
        if свои:
            поймано += 1
        else:
            пропущенные.append(имя)

    print(f"подложено {подложено}, поймано {поймано}, пропущено {len(пропущенные)}")
    for имя in пропущенные:
        print(f"   🔴 не сработало: {имя}")

    чистый = "def сложить(а, б):\n    return а + б\n# обычный код без значений\n"
    ложные = найти(чистый, "чистый")
    print(f"на чистом тексте находок: {len(ложные)} (обязан быть 0)")

    на_себе = найти(прочитать(Path(__file__)), "сам файл")
    print(f"на собственном исходнике находок: {len(на_себе)} (обязан быть 0)")
    for _, имя, номер, кратко in на_себе:
        print(f"   🔴 {номер}: {имя} — {кратко}")

    беды = len(пропущенные) + len(ложные) + len(на_себе)
    print()
    if беды:
        print(f"🔴 ВЕРДИКТ: сеть НЕ откалибрована — {беды} расхождений")
        return 1
    print("ВЕРДИКТ: сеть откалибрована, показания принимаются")
    return 0


def доложить(находки: list, сколько: int, что: str) -> int:
    # Ф-28: ноль печатается вместе с числом проверенного и с областью.
    print(f"проверено {что}: {сколько}")
    print(f"правил в сети: {len(ПРАВИЛА)}")
    if not находки:
        print("находок: 0 — ни одно правило сети не сработало")
        print("⚠️ это НЕ значит «секретов нет»: область сети названа в шапке файла")
        return 0
    print(f"🔴 НАХОДОК: {len(находки)}")
    for откуда, имя, номер, кратко in находки:
        print(f"   {откуда}:{номер} — {имя}\n      {кратко}")
    print("\n🔴 ОТКАЗ: фиксация не проходит, пока находки не разобраны.")
    return 1


def главное() -> int:
    р = argparse.ArgumentParser(description="Сеть на секреты при фиксации")
    р.add_argument("файлы", nargs="*", help="файлы для проверки")
    р.add_argument("--фиксация", action="store_true", help="то, что в индексе git")
    р.add_argument("--диапазон", help="содержимое коммитов, например d8bff09..HEAD")
    р.add_argument("--проба", action="store_true", help="калибровка образцами")
    а = р.parse_args()

    if а.проба:
        return проба()

    if а.диапазон:
        пары, что = из_диапазона(а.диапазон), "версий файлов в истории"
    elif а.файлы:
        пары, что = [(ф, прочитать(Path(ф))) for ф in а.файлы], "файлов"
    else:
        пары, что = из_индекса(), "файлов в индексе"

    находки = []
    for откуда, содержимое in пары:
        находки.extend(найти(содержимое, откуда))
    return доложить(находки, len(пары), что)


if __name__ == "__main__":
    raise SystemExit(главное())
